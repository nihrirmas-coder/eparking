#code taek cok ga rapi blas

parkir = {}
slot_terisi = []

while True:
  print(" ============================\n", "e-parking Restaurant\n","============================")
  print("apakah kendaraan masuk atau keluar\n", "1 - kendaraan masuk\n", "2 - kendaraan keluar\n","3 - Exit program\n" "============================")
  pilihan = input(" pilih 1, 2 atau 3 : ").lower()
  if pilihan == "1":

    while True:
     waktu = input(" masukkan waktu, (jam.menit) contoh: 18.20: ")
     jam1, menit1 = map(int, waktu.split("."))
     if jam1 <0 or menit1 < 0 or menit1 > 59 or jam1 > 23:
      print("Waktu tidak valid, Silahkan isi kembali")
     else:
      break

    while True:
     plat = input(" Masukkan Plat nomer anda: ").upper().strip()
     print("Slot yang terisi: ", slot_terisi )
     if plat in parkir:
      print("[error] : plat nomor tersebut sudah terdaftar. silahkan masukkan plat nomor anda dengan benar")
     elif len(plat) == 8 and plat[0].isalpha() and plat[1:5].isdigit() and plat[5:].isalpha():
      break
     elif len(plat) == 7 and plat[0].isalpha() and plat[1:5].isdigit() and plat[5:].isalpha():
      break
     elif plat[0:2].isalpha() and plat[2:6].isdigit() and plat[6:].isalpha():
      break
     else:
      print("[error]: format plat nomor salah")

    while True:
      pilih_slot = input(" pilih slot parkir yang tersedia (A1 - A99): ").capitalize()
      if pilih_slot in slot_terisi:
        print("\n Pemilihan slot gagal", pilih_slot, "Sudah terisi\n")
        print("=========== Silahkan isi kembali ===========\n")
      elif len(pilih_slot) == 3 and pilih_slot[0] == "A" and pilih_slot[1:3].isdigit():
        print("\n==========\nPemilihan slot berhasil, silahkan masuk\n==========\n")

        parkir[plat] = {
            "waktu_masuk": waktu,
            "jam1": jam1,
            "menit1": menit1,
            "slot": pilih_slot
        }
        slot_terisi.append(pilih_slot)

        break
      elif len(pilih_slot) == 2 and pilih_slot[0] == "A" and pilih_slot[1] in {"1", "2", "3", "4", "5", "6","7","8","9"}:
        print("\n==========\nPemilihan slot berhasil, silahkan masuk\n==========\n")

        parkir[plat] = {
            "waktu_masuk": waktu,
            "jam1": jam1,
            "menit1": menit1,
            "slot": pilih_slot
        }
        slot_terisi.append(pilih_slot)

        break
      else:
        print("pemilihan Slot tidak Valid")
        print("=========== Silahkan isi kembali ===========\n")

  elif pilihan == "2" and len(parkir) == 0:
    print("\n[Error]: tidak ada kendaraan masuk yang tercatat, silahkan pilih kembali")

  elif pilihan == "2":
    plat2 = input("masukkan plat nomor (tanpa spasi): ").upper().strip()
    if plat2 in parkir:
      while True:
       waktu_keluar = input(" masukkan waktu ketika keluar, (jam.menit) contoh: 18.20: ")
       continue
       if waktu_keluar[2] != ".":
        print("Format waktu salah, Gunakan '.' setelah jam")
       jam2, menit2 = map(int, waktu_keluar.split("."))
       if jam2 < 0 or menit2 <0  or menit2 > 59 or jam2 > 23:
        print("Waktu tidak valid, Silahkan isi kembali")
       else:
        break

      W2 = jam2 * 60 + menit2

      data_kendaraan = parkir[plat2]
      W1 = data_kendaraan["jam1"] * 60 + data_kendaraan["menit1"]

      if W1 > W2:
        W2 += 24 * 60
      selisih = W2 - W1
      if selisih < 1:
         selisih = 1
      selisih_jam = (selisih / 60)
      harga_tiket = 2000 * selisih_jam

      print("------------ struk parkir ------------")
      print("Plat nomor           :", plat2)
      print("waktu masuk          :", data_kendaraan["waktu_masuk"])
      print("waktu keluar         :", waktu_keluar)
      print("total jam masuk      :", selisih_jam )
      print("harga parkir per jam : 2000" )
      print("Slot parkir          :", data_kendaraan["slot"])
      print("\ntotal harga        :", int(harga_tiket))
      print("--------------------------------------")
      print("  Terimakasih atas kunjungan anda \n")

      slot_terisi.remove(data_kendaraan["slot"])
      parkir.pop(plat2)
    else:
      print("\n[Error] : Kendaraan dengan plat tersebut tidak ditemukan di parkiran\n")
  elif pilihan == "3":
    print("terimakasih telah menggunakan program kami")
    break
  else:
    print("\033[31m Error: input tidak ada dalam menu\033[0m")